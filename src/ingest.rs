    async fn corrected_revision_does_not_mutate_old_evidence() {
        let db = SqlitePool::connect("sqlite::memory:").await.unwrap();
        sqlx::raw_sql(include_str!("../migrations/0001_initial.sql"))
            .execute(&db)
            .await
            .unwrap();
        sqlx::raw_sql(include_str!("../migrations/0003_knowledge_workflow.sql"))
            .execute(&db)
            .await
            .unwrap();
        sqlx::query("INSERT INTO kb_course_nodes(node_id,course_id,level,title) VALUES('leaf','course',2,'Leaf')").execute(&db).await.unwrap();
        sqlx::query("INSERT INTO kb_assets(asset_id,node_id,asset_type,original_name,storage_key,byte_size,created_by) VALUES('asset','leaf','text','source.txt','safe.txt',4,'admin')").execute(&db).await.unwrap();
        let mut tx = db.begin().await.unwrap();
        insert_revision(
            &mut tx,
            "revision-1",
            "asset",
            1,
            "sourcehash",
            &json!({}),
            "admin",
        )
        .await
        .unwrap();
        let original_part = insert_part(
            &mut tx,
            "revision-1",
            0,
            "text",
            Some("original"),
            None,
            None,
            None,
            None,
            &json!({}),
        )
        .await
        .unwrap();
        tx.commit().await.unwrap();
        let old_row = sqlx::query("SELECT * FROM kb_content_parts WHERE part_id=?")
            .bind(&original_part)
            .fetch_one(&db)
            .await
            .unwrap();
        let mut tx = db.begin().await.unwrap();
        let (next, number) = next_revision(&mut tx, "asset", Some("revision-1"), "admin")
            .await
            .unwrap();
        assert_eq!(number, 2);
        let corrected_part = clone_part(&mut tx, &next, 0, &old_row, Some("corrected"))
            .await
            .unwrap();
        tx.commit().await.unwrap();
        let original: String =
            sqlx::query_scalar("SELECT content_text FROM kb_content_parts WHERE part_id=?")
                .bind(original_part)
                .fetch_one(&db)
                .await
                .unwrap();
        assert_eq!(original, "original");
        let corrected: (String, String) = sqlx::query_as(
            "SELECT content_text,evidence_status FROM kb_content_parts WHERE part_id=?",
        )
        .bind(corrected_part)
        .fetch_one(&db)
        .await
        .unwrap();
        assert_eq!(corrected, ("corrected".into(), "pending".into()));
        let mut tx = db.begin().await.unwrap();
        assert!(next_revision(&mut tx, "asset", Some("revision-1"), "admin")
            .await
            .is_err());
    }
