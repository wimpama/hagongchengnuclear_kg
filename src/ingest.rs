async fn next_revision(
    tx: &mut Transaction<'_, Sqlite>,
    asset: &str,
    expected_revision: Option<&str>,
    actor: &str,
) -> Result<(String, i64), ApiError> {
    let row = sqlx::query("SELECT r.revision_id,r.source_sha256,r.revision_number FROM kb_asset_revisions r JOIN kb_assets a ON a.asset_id=r.asset_id JOIN kb_course_nodes n ON n.node_id=a.node_id WHERE r.asset_id=? AND a.deleted_at IS NULL AND n.level=2 AND n.is_active=1 ORDER BY revision_number DESC LIMIT 1").bind(asset).fetch_optional(&mut **tx).await?.ok_or_else(||ApiError::not_found("资料已失效"))?;
    if expected_revision != Some(row.get::<String, _>("revision_id").as_str()) {
        return Err(ApiError::bad_request("资料已更新，请刷新后重试"));
    }
    let hash: String = row.get("source_sha256");
    let number = row.get::<i64, _>("revision_number") + 1;
    let id = Uuid::new_v4().to_string();
    insert_revision(tx, &id, asset, number, &hash, &json!({"state":"review_required","message":"教师内容已更新，需要重新审核、索引并发布；旧发布版本保持不变"}), actor).await?;
    Ok((id, number))
}

async fn clone_part(
    tx: &mut Transaction<'_, Sqlite>,
    revision: &str,
    index: usize,
    row: &sqlx::sqlite::SqliteRow,
    replacement: Option<&str>,
) -> Result<String, ApiError> {
    let old_text: Option<String> = row.get("content_text");
    let media: Option<String> = row.get("media_storage_key");
    let modality: String = row.get("modality");
    let raw_metadata: Option<String> = row.get("metadata_json");
    let mut metadata: Value = raw_metadata
        .and_then(|s| serde_json::from_str(&s).ok())
        .unwrap_or_else(|| json!({}));
    if !metadata.is_object() {
        metadata = json!({});
    }
    if replacement.is_some() {
        metadata["source"] = json!("teacher_text");
        metadata["needsDescription"] = json!(false);
    }
    insert_part(
        tx,
        revision,
        index,
        &modality,
        replacement.or(old_text.as_deref()),
        media.as_deref(),
        row.get("page_number"),
        row.get("start_ms"),
        row.get("end_ms"),
        &metadata,
    )
    .await
}

async fn delete_asset(
    State(state): State<AppState>,
    headers: HeaderMap,
    Path(asset_id): Path<String>,
) -> Result<StatusCode, ApiError> {
    let user = require_admin(&state, &headers).await?;
    // Retraction must remain possible after a catalog sync deactivates or
    // removes the node; deleting an old asset is itself part of cleanup.
    let exists: Option<String> = sqlx::query_scalar(
        "SELECT asset_id FROM kb_assets WHERE asset_id=? AND deleted_at IS NULL",
    )
    .bind(&asset_id)
    .fetch_optional(&state.db)
    .await?;
    if exists.is_none() {
        return Err(ApiError::not_found("资料不存在或已删除"));
    }
    let mut tx = state.db.begin().await?;
    sqlx::query("UPDATE kb_assets SET published_revision_id=NULL,deleted_at=CURRENT_TIMESTAMP WHERE asset_id=?").bind(&asset_id).execute(&mut *tx).await?;
    sqlx::query("UPDATE kb_asset_revisions SET status='withdrawn' WHERE asset_id=?")
        .bind(&asset_id)
        .execute(&mut *tx)
        .await?;
    sqlx::query("UPDATE kb_jobs SET state='cancelled',finished_at=CURRENT_TIMESTAMP WHERE asset_id=? AND state IN ('queued','running')").bind(&asset_id).execute(&mut *tx).await?;
    // Keep the original until asynchronous vector/file cleanup has completed.
    sqlx::query(
        "INSERT INTO kb_jobs(job_id,job_type,asset_id,state) VALUES(?,'asset_cleanup',?,'queued')",
    )
    .bind(Uuid::new_v4().to_string())
    .bind(&asset_id)
    .execute(&mut *tx)
    .await?;
    audit(
        &mut tx,
        &user.id,
        "asset.delete",
        &asset_id,
        json!({"published":false}),
    )
    .await?;
    tx.commit().await?;
    Ok(StatusCode::NO_CONTENT)
}

