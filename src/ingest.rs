const MAX_FILE_BYTES: usize = 100 * 1024 * 1024;
const MAX_IMAGE_BYTES: usize = 20 * 1024 * 1024;
const MAX_TEXT_BYTES: usize = 10 * 1024 * 1024;
const PARSER_VERSION: &str = "bounded-ooxml-math-v2";

pub fn router() -> Router<AppState> {
    Router::new()
        .route(
            "/kb-api/v1/admin/nodes/{node_id}/knowledge",
            get(list_assets),
        )
        .route(
            "/kb-api/v1/admin/nodes/{node_id}/knowledge/assets",
            post(upload_asset),
        )
        .route(
            "/kb-api/v1/admin/nodes/{node_id}/knowledge/import-courseware",
            post(import_courseware),
        )
        .route(
            "/kb-api/v1/admin/knowledge/assets/{asset_id}",
            get(get_asset).delete(delete_asset),
        )
        .route(
            "/kb-api/v1/admin/knowledge/assets/{asset_id}/parts",
            get(get_parts),
        )
        .route(
            "/kb-api/v1/admin/knowledge/assets/{asset_id}/text",
            patch(replace_asset_text),
        )
        .route(
            "/kb-api/v1/admin/knowledge/parts/{part_id}",
            patch(update_part),
        )
        .layer(DefaultBodyLimit::max(
            MAX_FILE_BYTES + 2 * MAX_TEXT_BYTES + 64 * 1024,
        ))
}

/// The stored key is always generated by this module, never a client path.
#[cfg(test)]
pub fn uploads_dir() -> PathBuf {
    env::var_os("KB_UPLOADS_DIR")
        .map(PathBuf::from)
        .or_else(|| env::var_os("KB_DATA_DIR").map(|value| PathBuf::from(value).join("uploads")))
        .unwrap_or_else(|| PathBuf::from("data/uploads"))
}

pub async fn require_active_leaf(db: &SqlitePool, node_id: &str) -> Result<(), ApiError> {
    let valid: i64 = sqlx::query_scalar(
        "SELECT COUNT(*) FROM kb_course_nodes WHERE node_id=? AND level=2 AND is_active=1",
    )
    .bind(node_id)
    .fetch_one(db)
    .await?;
    if valid != 1 {
        return Err(ApiError::bad_request("请先同步有效的二级课程节点"));
    }
    Ok(())
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
pub struct AssetView {
    pub id: String,
    pub node_id: String,
    pub name: String,
    pub mime_type: Option<String>,
    pub size_bytes: i64,
    pub status: String,
    pub vector_status: String,
    pub review_status: String,
    pub published: bool,
    pub revision_id: Option<String>,
    pub extraction: Option<Value>,
    pub last_error: Option<String>,
    pub index_job_state: Option<String>,
    pub index_progress: Option<Value>,
    pub created_at: String,
}

fn asset_from_row(row: &sqlx::sqlite::SqliteRow) -> AssetView {
    let extraction: Option<String> = row.get("extraction_json");
    AssetView {
        id: row.get("asset_id"),
        node_id: row.get("node_id"),
        name: row.get("original_name"),
        mime_type: row.get("mime_type"),
        size_bytes: row.get("byte_size"),
        status: row
            .try_get::<Option<String>, _>("status")
            .ok()
            .flatten()
            .unwrap_or_else(|| "draft".into()),
        vector_status: row
            .try_get::<Option<String>, _>("index_status")
            .ok()
            .flatten()
            .unwrap_or_else(|| "pending".into()),
        review_status: row
            .try_get::<Option<String>, _>("review_status")
            .ok()
            .flatten()
            .unwrap_or_else(|| "pending".into()),
        published: row
            .get::<Option<String>, _>("published_revision_id")
            .is_some(),
        revision_id: row.get("revision_id"),
        extraction: extraction.and_then(|s| serde_json::from_str(&s).ok()),
        // Job errors are bounded application messages, never raw provider bodies.
        last_error: row
            .try_get::<Option<String>, _>("last_index_error")
            .ok()
            .flatten()
            .map(|value| value.chars().take(500).collect()),
        index_job_state: row.try_get("index_job_state").ok().flatten(),
        index_progress: row.try_get::<Option<String>, _>("index_job_state").ok().flatten().map(|state| {
            let completed = row.try_get::<Option<i64>, _>("progress_completed").ok().flatten().unwrap_or(0);
            let total = row.try_get::<Option<i64>, _>("progress_total").ok().flatten().unwrap_or(0);
            let percent = if state == "succeeded" { 100 } else if total > 0 { (completed * 100 / (total + 1)).min(99) } else { 0 };
            json!({"completed":completed,"total":total,"percent":percent,
                "stage":if state == "succeeded" { "complete".to_owned() } else { row.try_get::<Option<String>, _>("progress_stage").ok().flatten().unwrap_or(state) }})
        }),
        created_at: row.get("created_at"),
    }
}

const ASSET_SELECT: &str = "SELECT a.*,r.revision_id,r.status,r.review_status,r.index_status,r.extraction_json,j.state AS index_job_state,j.progress_completed,j.progress_total,j.progress_stage,CASE WHEN j.state IN ('failed','queued') THEN j.error_message END AS last_index_error FROM kb_assets a LEFT JOIN kb_asset_revisions r ON r.revision_id=(SELECT revision_id FROM kb_asset_revisions WHERE asset_id=a.asset_id ORDER BY revision_number DESC LIMIT 1) LEFT JOIN kb_jobs j ON j.job_id=(SELECT job_id FROM kb_jobs WHERE revision_id=r.revision_id AND job_type='index_revision' ORDER BY rowid DESC LIMIT 1)";

pub async fn load_asset(db: &SqlitePool, asset_id: &str) -> Result<AssetView, ApiError> {
    let row = sqlx::query(&format!(
        "{ASSET_SELECT} WHERE a.asset_id=? AND a.deleted_at IS NULL"
    ))
    .bind(asset_id)
    .fetch_optional(db)
    .await?
    .ok_or_else(|| ApiError::not_found("资料不存在或已删除"))?;
    let view = asset_from_row(&row);
    require_active_leaf(db, &view.node_id).await?;
    Ok(view)
}

async fn list_assets(
    State(state): State<AppState>,
    headers: HeaderMap,
    Path(node_id): Path<String>,
) -> Result<Json<Vec<AssetView>>, ApiError> {
    require_admin(&state, &headers).await?;
    require_active_leaf(&state.db, &node_id).await?;
    let rows = sqlx::query(&format!("{ASSET_SELECT} WHERE a.node_id=? AND a.deleted_at IS NULL ORDER BY a.created_at DESC,a.asset_id"))
        .bind(node_id).fetch_all(&state.db).await?;
    Ok(Json(rows.iter().map(asset_from_row).collect()))
}

async fn get_asset(
    State(state): State<AppState>,
    headers: HeaderMap,
    Path(asset_id): Path<String>,
) -> Result<Json<AssetView>, ApiError> {
    require_admin(&state, &headers).await?;
    Ok(Json(load_asset(&state.db, &asset_id).await?))
}

struct StoredFile {
    path: PathBuf,
    storage_key: String,
    name: String,
    mime: String,
    kind: &'static str,
    size: usize,
    hash: String,
    retained: bool,
    remote_started: bool,
    storage: crate::storage::BlobStore,
}
impl Drop for StoredFile {
    fn drop(&mut self) {
        // Also clean up a partially streamed upload on cancellation/error.
        if !self.retained {
            let _ = std::fs::remove_file(&self.path);
            if self.remote_started && self.storage.is_remote() {
                let storage = self.storage.clone();
                let key = self.storage_key.clone();
                tokio::spawn(async move {
                    if storage.delete(&key).await.is_err() {
                        tracing::warn!(storage_key = %key, "failed to clean up uncommitted OSS upload");
                    }
                });
            }
        }
    }
}

async fn upload_asset(
    State(state): State<AppState>,
    headers: HeaderMap,
    Path(node_id): Path<String>,
    mut multipart: Multipart,
) -> Result<(StatusCode, Json<AssetView>), ApiError> {
    let user = require_admin(&state, &headers).await?;
    require_active_leaf(&state.db, &node_id).await?;
    let root = state.storage.local_dir().to_owned();
    tokio::fs::create_dir_all(&root)
        .await
        .map_err(|_| ApiError::internal())?;
    let mut uploaded: Option<StoredFile> = None;
    let mut title: Option<String> = None;
    let mut description: Option<String> = None;
    let mut subtitle: Option<String> = None;
    let mut seen_fields = std::collections::HashSet::new();
    while let Some(mut field) = multipart
        .next_field()
        .await
        .map_err(|_| ApiError::bad_request("上传表单无效或超过大小限制"))?
    {
        let field_name = field.name().map(str::to_owned).unwrap_or_default();
        if !matches!(
            field_name.as_str(),
            "file" | "title" | "description" | "subtitle"
        ) || !seen_fields.insert(field_name.clone())
        {
            return Err(ApiError::bad_request("上传表单包含重复或未知字段"));
        }
        if matches!(field_name.as_str(), "title" | "description" | "subtitle") {
            if field.file_name().is_some() {
                return Err(ApiError::bad_request("标题、说明和字幕应以 UTF-8 文本提交"));
            }
            let mut text = Vec::new();
            while let Some(chunk) = field
                .chunk()
                .await
                .map_err(|_| ApiError::bad_request("上传文本字段无效"))?
            {
                let limit = if field_name == "title" {
                    1024
                } else {
                    MAX_TEXT_BYTES
                };
                if text.len() + chunk.len() > limit {
                    return Err(ApiError::bad_request(if field_name == "title" {
                        "标题过长"
                    } else {
                        "正文或字幕文件不得超过 10MB"
                    }));
                }
                text.extend_from_slice(&chunk);
            }
            let value = String::from_utf8(text)
                .map_err(|_| ApiError::bad_request("正文、字幕和标题应为 UTF-8"))?
                .trim_start_matches('\u{feff}')
                .trim()
                .to_owned();
            if value.contains('\0') {
                return Err(ApiError::bad_request("上传文本不能包含二进制数据"));
            }
            match field_name.as_str() {
                "title" => title = Some(value),
                "description" => description = Some(value),
                "subtitle" => subtitle = Some(value),
                _ => unreachable!(),
            }
            continue;
        }
        if field_name != "file" || uploaded.is_some() {
            return Err(ApiError::bad_request("每次只能上传一个资料文件"));
        }
        let name = safe_display_name(
            field
                .file_name()
                .ok_or_else(|| ApiError::bad_request("缺少文件名"))?,
        )?;
        let extension = FsPath::new(&name)
            .extension()
            .and_then(|v| v.to_str())
            .unwrap_or("")
            .to_ascii_lowercase();
        let (kind, canonical_mime) =
            file_type(&extension).ok_or_else(|| ApiError::bad_request("不支持此文件格式"))?;
        let declared_mime = field
            .content_type()
            .unwrap_or("application/octet-stream")
            .split(';')
            .next()
            .unwrap_or("")
            .trim()
            .to_ascii_lowercase();
        if !mime_matches(&extension, &declared_mime, canonical_mime) {
            return Err(ApiError::bad_request("文件 MIME 与扩展名不一致"));
        }
        let storage_key = format!("{}.{}", Uuid::new_v4(), extension);
        let path = root.join(&storage_key);
        let mut stored = StoredFile {
            path: path.clone(),
            storage_key,
            name,
            mime: canonical_mime.into(),
            kind,
            size: 0,
            hash: String::new(),
            retained: false,
            remote_started: false,
            storage: state.storage.clone(),
        };
        let mut file = tokio::fs::OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(&path)
            .await
            .map_err(|_| ApiError::internal())?;
        let mut digest = Sha256::new();
        let mut prefix = Vec::new();
        while let Some(chunk) = field
            .chunk()
            .await
            .map_err(|_| ApiError::bad_request("文件上传中断或超过大小限制"))?
        {
            stored.size = stored
                .size
                .checked_add(chunk.len())
                .ok_or_else(|| ApiError::bad_request("文件过大"))?;
            if stored.size > MAX_FILE_BYTES {
                return Err(ApiError::bad_request("单文件不得超过 100MB"));
            }
            if stored.kind == "image" && stored.size > MAX_IMAGE_BYTES {
                return Err(ApiError::bad_request("图片不得超过 20MB，请缩小后上传"));
            }
            if prefix.len() < 512 {
                prefix.extend_from_slice(&chunk[..chunk.len().min(512 - prefix.len())]);
            }
            digest.update(&chunk);
            file.write_all(&chunk)
                .await
                .map_err(|_| ApiError::internal())?;
        }
        file.flush().await.map_err(|_| ApiError::internal())?;
        drop(file);
        if stored.size == 0 || !magic_matches(&extension, &prefix) {
            return Err(ApiError::bad_request("文件为空或实际内容与格式不符"));
        }
        stored.hash = format!("{:x}", digest.finalize());
        uploaded = Some(stored);
    }
    let stored = uploaded.ok_or_else(|| ApiError::bad_request("请选择一个文件"))?;
    let asset = finish_asset(
        &state,
        &user,
        &node_id,
        stored,
        UploadFields {
            title,
            description,
            subtitle,
        },
        None,
    )
    .await?;
    Ok((StatusCode::CREATED, Json(asset)))
}

#[derive(Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct CoursewareImportRequest {
    courseware_id: String,
    title: Option<String>,
    description: Option<String>,
    subtitle: Option<String>,
}

async fn import_courseware(
    State(state): State<AppState>,
    headers: HeaderMap,
    Path(node_id): Path<String>,
    Json(request): Json<CoursewareImportRequest>,
) -> Result<(StatusCode, Json<AssetView>), ApiError> {
    let user = require_admin(&state, &headers).await?;
    let fields = UploadFields {
        title: request.title,
        description: request.description,
        subtitle: request.subtitle,
    }
    .normalized()?;
    let source =
        crate::courseware::resolve_import(&state, &headers, &node_id, &request.courseware_id)
            .await?;
    let root = state.storage.local_dir();
    tokio::fs::create_dir_all(root)
        .await
        .map_err(|_| ApiError::internal())?;
    let storage_key = format!("{}.{}", Uuid::new_v4(), source.extension);
    let mut stored = StoredFile {
        path: root.join(&storage_key),
        storage_key,
        name: safe_display_name(&source.name)?,
        mime: source.mime.into(),
        kind: source.kind,
        size: 0,
        hash: String::new(),
        retained: false,
        remote_started: false,
        storage: state.storage.clone(),
    };
    let client = reqwest::Client::builder()
        .redirect(reqwest::redirect::Policy::none())
        .connect_timeout(std::time::Duration::from_secs(15))
        .timeout(std::time::Duration::from_secs(180))
        .build()
        .map_err(|_| ApiError::internal())?;
    // No course Bearer token or OSS credential is sent to the source CDN.
    let mut response = client
        .get(source.url)
        .send()
        .await
        .map_err(|_| ApiError::unavailable("读取课件原件失败，请稍后重新导入"))?;
    if !response.status().is_success() {
        return Err(ApiError::unavailable(
            "课件原件暂不可用，链接可能已失效，请刷新课件列表后重试",
        ));
    }
    let limit = match stored.kind {
        "image" => MAX_IMAGE_BYTES,
        "text" => MAX_TEXT_BYTES,
        _ => MAX_FILE_BYTES,
    };
    if response
        .content_length()
        .is_some_and(|size| size > limit as u64)
    {
        return Err(ApiError::bad_request("课件超过该格式的导入大小限制"));
    }
    let supplied_mime = response
        .headers()
        .get(reqwest::header::CONTENT_TYPE)
        .and_then(|value| value.to_str().ok())
        .unwrap_or("application/octet-stream")
        .split(';')
        .next()
        .unwrap_or_default()
        .trim()
        .to_ascii_lowercase();
    if !mime_matches(&source.extension, &supplied_mime, &stored.mime) {
        return Err(ApiError::bad_request("课件原件的 MIME 与文件格式不一致"));
    }
    let mut file = tokio::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&stored.path)
        .await
        .map_err(|_| ApiError::internal())?;
    let mut digest = Sha256::new();
    let mut prefix = Vec::new();
    while let Some(chunk) = response
        .chunk()
        .await
        .map_err(|_| ApiError::unavailable("读取课件原件中断，请重新导入"))?
    {
        stored.size = stored
            .size
            .checked_add(chunk.len())
            .filter(|size| *size <= limit)
            .ok_or_else(|| ApiError::bad_request("课件超过该格式的导入大小限制"))?;
        if prefix.len() < 512 {
            prefix.extend_from_slice(&chunk[..chunk.len().min(512 - prefix.len())]);
        }
        digest.update(&chunk);
        file.write_all(&chunk)
            .await
            .map_err(|_| ApiError::internal())?;
    }
    file.flush().await.map_err(|_| ApiError::internal())?;
    drop(file);
    if stored.size == 0 || !magic_matches(&source.extension, &prefix) {
        return Err(ApiError::bad_request("课件为空或实际内容与文件格式不符"));
    }
    stored.hash = format!("{:x}", digest.finalize());
    let asset = finish_asset(&state, &user, &node_id, stored, fields, Some(source.id)).await?;
    Ok((StatusCode::CREATED, Json(asset)))
}

#[derive(Default)]
struct UploadFields {
    title: Option<String>,
    description: Option<String>,
    subtitle: Option<String>,
}

impl UploadFields {
    fn normalized(self) -> Result<Self, ApiError> {
        fn field(value: Option<String>, maximum: usize) -> Result<Option<String>, ApiError> {
            value
                .map(|text| {
                    if text.len() > maximum || text.contains('\0') {
                        return Err(ApiError::bad_request("标题、说明或字幕无效或超过大小限制"));
                    }
                    Ok(text.trim_start_matches('\u{feff}').trim().to_owned())
                })
                .transpose()
        }
        Ok(Self {
            title: field(self.title, 1024)?,
            description: field(self.description, MAX_TEXT_BYTES)?,
            subtitle: field(self.subtitle, MAX_TEXT_BYTES)?,
        })
    }
}

async fn finish_asset(
    state: &AppState,
    user: &crate::auth::AuthenticatedUser,
    node_id: &str,
    mut stored: StoredFile,
    fields: UploadFields,
    source_courseware_id: Option<String>,
) -> Result<AssetView, ApiError> {
    let UploadFields {
        title,
        description,
        subtitle,
    } = fields.normalized()?;
    let description = description.as_deref().filter(|value| !value.is_empty());
    let subtitle = subtitle.as_deref().filter(|value| !value.is_empty());
    if subtitle.is_some() && !matches!(stored.kind, "audio" | "video") {
        return Err(ApiError::bad_request("字幕仅适用于视频或音频资料"));
    }
    if stored.kind == "audio" && subtitle.is_none() {
        return Err(ApiError::bad_request(
            "自动语音转写尚未接入，音频请同时提供字幕或转写文本",
        ));
    }
    let subtitle_cues = subtitle
        .map(parse_subtitles)
        .transpose()?
        .unwrap_or_default();
    let mut document_message = String::new();
    let mut prepared_document = None;
    let extracted = if stored.kind == "text" {
        if stored.size > MAX_TEXT_BYTES {
            return Err(ApiError::bad_request("文本资料不得超过 10MB，请拆分后上传"));
        }
        let bytes = tokio::fs::read(&stored.path)
            .await
            .map_err(|_| ApiError::internal())?;
        let text = std::str::from_utf8(&bytes)
            .map_err(|_| ApiError::bad_request("文本请使用 UTF-8 编码"))?;
        if text.contains('\0') {
            return Err(ApiError::bad_request("文本包含二进制数据"));
        }
        let ext = FsPath::new(&stored.storage_key)
            .extension()
            .and_then(|s| s.to_str())
            .unwrap_or("")
            .to_ascii_lowercase();
        let text = if ext == "html" || ext == "htm" {
            html_text(text)
        } else if ext == "csv" {
            csv_text(text)?
        } else {
            text.trim_start_matches('\u{feff}').trim().to_owned()
        };
        if text.is_empty() {
            return Err(ApiError::bad_request("文件未提取到有效正文"));
        }
        vec![crate::extract::ExtractedPage {
            text,
            page: None,
            image_key: None,
        }]
    } else if stored.kind == "document" {
        let mut parsed =
            crate::document_visuals::prepare(&state.storage, &stored.storage_key, &stored.mime)
                .await?;
        document_message = parsed.message.clone();
        let pages = std::mem::take(&mut parsed.pages);
        prepared_document = Some(parsed);
        pages
    } else {
        vec![]
    };
    let asset_id = Uuid::new_v4().to_string();
    let revision_id = Uuid::new_v4().to_string();
    let display_name = title
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| stored.name.clone());
    if display_name.chars().count() > 255 || display_name.chars().any(char::is_control) {
        return Err(ApiError::bad_request(
            "资料名称不得超过 255 个字符或包含控制字符",
        ));
    }
    // The local file is the parser/ffmpeg working copy. In OSS mode upload it
    // before publishing metadata so every newly accepted course resource has
    // a durable object even when the process is later replaced.
    stored.remote_started = true;
    state
        .storage
        .put_file(&stored.storage_key, &stored.path, &stored.mime)
        .await?;
    let mut tx = state.db.begin().await?;
    let valid: i64 = sqlx::query_scalar(
        "SELECT COUNT(*) FROM kb_course_nodes WHERE node_id=? AND level=2 AND is_active=1",
    )
    .bind(node_id)
    .fetch_one(&mut *tx)
    .await?;
    if valid != 1 {
        return Err(ApiError::bad_request(
            "上传期间课程节点已变化，请重新同步后上传",
        ));
    }
    sqlx::query("INSERT INTO kb_assets(asset_id,node_id,asset_type,original_name,storage_key,byte_size,mime_type,created_by) VALUES(?,?,?,?,?,?,?,?)")
        .bind(&asset_id).bind(node_id).bind(stored.kind).bind(display_name).bind(&stored.storage_key).bind(stored.size as i64).bind(&stored.mime).bind(&user.id).execute(&mut *tx).await?;
    let mut extraction = upload_extraction(
        stored.kind,
        &stored.name,
        !extracted.is_empty(),
        description.is_some(),
        !subtitle_cues.is_empty(),
        &document_message,
    );
    let visual_pages = extracted.iter().filter(|p| p.image_key.is_some()).count();
    if visual_pages > 0 {
        extraction["extractionMode"] = json!("page_text_image_v1");
        extraction["pageCount"] = json!(extracted.len());
        extraction["visualPageCount"] = json!(visual_pages);
    }
    if let Some(id) = source_courseware_id.as_deref() {
        extraction["sourceCoursewareId"] = json!(id);
        extraction["sourceType"] = json!("courseware_snapshot");
    }
    insert_revision(
        &mut tx,
        &revision_id,
        &asset_id,
        1,
        &stored.hash,
        &extraction,
        &user.id,
    )
    .await?;
    insert_upload_parts(
        &mut tx,
        &revision_id,
        stored.kind,
        &stored.storage_key,
        &extracted,
        description,
        &subtitle_cues,
    )
    .await?;
    audit(
        &mut tx,
        &user.id,
        if source_courseware_id.is_some() { "asset.import_courseware" } else { "asset.upload" },
        &asset_id,
        json!({"revisionId":revision_id,"sha256":stored.hash,"sizeBytes":stored.size,"sourceCoursewareId":source_courseware_id}),
    )
    .await?;
    tx.commit().await?;
    stored.retained = true;
    if let Some(mut document) = prepared_document {
        document.retain();
    }
    load_asset(&state.db, &asset_id).await
}

fn upload_extraction(
    kind: &str,
    source_name: &str,
    extracted: bool,
    description: bool,
    subtitle: bool,
    document_message: &str,
) -> Value {
    let (state, message) = match kind {
        "image" => (
            "review_required",
            "图片已保存，可直接进行视觉索引；教师说明可选，请确认图片内容后审核",
        ),
        "video" if !subtitle => (
            "review_required",
            "视频已保存；未提供字幕，审核后仅可索引画面，不能据声音回答问题",
        ),
        "audio" | "video" => (
            "review_required",
            "媒体及教师字幕已保存，请校对字幕后审核、索引并发布",
        ),
        "document" if extracted && !document_message.is_empty() => {
            ("review_required", document_message)
        }
        _ if extracted => ("review_required", "正文已提取，请校对后审核、索引并发布"),
        _ if description => ("review_required", "教师说明已保存，请审核后索引并发布"),
        _ => ("needs_description", document_message),
    };
    json!({"state":state,"sourceName":source_name,"message":message,"hasSubtitle":subtitle,"hasTeacherDescription":description})
}

#[allow(clippy::too_many_arguments)]
async fn insert_upload_parts(
    tx: &mut Transaction<'_, Sqlite>,
    revision: &str,
    kind: &str,
    source_key: &str,
    extracted: &[crate::extract::ExtractedPage],
    description: Option<&str>,
    subtitles: &[SubtitleCue],
) -> Result<(), ApiError> {
    let mut index = 0;
    for page in extracted {
        // Store one JPEG per page. Every text chunk is paired with that exact
        // page image, so dense pages retain precise recall and a correction
        // cannot leave behind a second copy of the old page text.
        let mut chunks = split_text(&page.text);
        if chunks.is_empty() && page.image_key.is_some() {
            chunks.push(String::new());
        }
        for (chunk_index, text) in chunks.iter().enumerate() {
            insert_part(
                tx,
                revision,
                index,
                if page.image_key.is_some() { "image" } else { "text" },
                (!text.is_empty()).then_some(text.as_str()),
                page.image_key.as_deref(),
                page.page,
                None,
                None,
                &json!({"source":"extracted","documentPage":page.image_key.is_some(),"pageChunk":chunk_index,"pageImageMime":page.image_key.as_deref().map(crate::document_visuals::page_image_mime)}),
            )
            .await?;
            index += 1;
        }
    }
    // An image description belongs to this exact image. Keeping it on an image
    // part also embeds the real visual rather than just the teacher's words.
    if kind == "image" {
        if let Some(description) = description {
            for text in split_text(description) {
                insert_part(
                    tx,
                    revision,
                    index,
                    "image",
                    Some(&text),
                    Some(source_key),
                    None,
                    None,
                    None,
                    &json!({"source":"teacher_description","needsDescription":false}),
                )
                .await?;
                index += 1;
            }
        } else {
            insert_part(
                tx,
                revision,
                index,
                "image",
                None,
                Some(source_key),
                None,
                None,
                None,
                &json!({"source":"original_media","needsDescription":false}),
            )
            .await?;
        }
        return Ok(());
    }
    let media = matches!(kind, "video" | "audio").then_some(source_key);
    if let Some(key) = media {
        insert_part(
            tx,
            revision,
            index,
            kind,
            None,
            Some(key),
            None,
            None,
            None,
            &json!({"source":"original_media","audioUnderstood":false,"needsDescription":false}),
        )
        .await?;
        index += 1;
    }
    if let Some(description) = description {
        for text in split_text(description) {
            // A general video description is not a subtitle and must never be
            // duplicated onto every prepared video segment during review.
            insert_part(
                tx,
                revision,
                index,
                "text",
                Some(&text),
                media,
                None,
                None,
                None,
                &json!({"source":"teacher_description","audioUnderstood":false}),
            )
            .await?;
            index += 1;
        }
    }
    append_subtitle_parts(tx, revision, &mut index, kind, media, subtitles).await
}

#[derive(Debug, PartialEq, Eq)]
struct SubtitleCue {
    text: String,
    start_ms: Option<i64>,
    end_ms: Option<i64>,
}

fn subtitle_timestamp(value: &str) -> Result<i64, ApiError> {
    let invalid =
        || ApiError::bad_request("字幕时间戳无效，请使用 SRT/VTT 格式或不带时间戳的纯文本");
    let value = value.replace(',', ".");
    let components: Vec<_> = value.split(':').collect();
    if !(2..=3).contains(&components.len()) {
        return Err(invalid());
    }
    let number = |part: &str| -> Result<i64, ApiError> {
        if part.is_empty() || !part.bytes().all(|b| b.is_ascii_digit()) {
            return Err(invalid());
        }
        part.parse().map_err(|_| invalid())
    };
    let hours = if components.len() == 3 {
        number(components[0])?
    } else {
        0
    };
    let minutes = number(components[components.len() - 2])?;
    let (seconds, millis) = components[components.len() - 1]
        .split_once('.')
        .ok_or_else(invalid)?;
    let seconds = number(seconds)?;
    if millis.is_empty() || millis.len() > 3 || hours > 8760 || minutes >= 60 || seconds >= 60 {
        return Err(invalid());
    }
    let millis = number(millis)? * 10_i64.pow((3 - millis.len()) as u32);
    let result = ((hours * 60 + minutes) * 60 + seconds) * 1000 + millis;
    if result > 31_536_000_000 {
        return Err(invalid());
    }
    Ok(result)
}

fn parse_subtitles(text: &str) -> Result<Vec<SubtitleCue>, ApiError> {
    let text = validate_text(text)?
        .trim_start_matches('\u{feff}')
        .replace("\r\n", "\n")
        .replace('\r', "\n");
    if text.trim().is_empty() {
        return Err(ApiError::bad_request("字幕正文不能为空"));
    }
    if !text.contains("-->") && !text.starts_with("WEBVTT") {
        return Ok(vec![SubtitleCue {
            text,
            start_ms: None,
            end_ms: None,
        }]);
    }
    let invalid = || ApiError::bad_request("字幕格式无效，请检查 SRT/VTT 时间戳、正文和空行分隔");
    let mut cues = Vec::new();
    // Whitespace-only lines also separate cues. VTT metadata/notes are never
    // promoted to source evidence.
    let mut blocks: Vec<Vec<&str>> = Vec::new();
    let mut current = Vec::new();
    for line in text.lines() {
        if line.trim().is_empty() {
            if !current.is_empty() {
                blocks.push(std::mem::take(&mut current));
            }
        } else {
            current.push(line);
        }
    }
    if !current.is_empty() {
        blocks.push(current);
    }
    for block in blocks {
        let first = block[0].trim();
        if first == "WEBVTT"
            || first.starts_with("WEBVTT ")
            || first == "STYLE"
            || first == "REGION"
            || first == "NOTE"
            || first.starts_with("NOTE ")
        {
            continue;
        }
        let timing = if first.contains("-->") { 0 } else { 1 };
        let timing_line = block.get(timing).ok_or_else(invalid)?;
        let (start, end) = timing_line.split_once("-->").ok_or_else(invalid)?;
        let start_ms = subtitle_timestamp(start.trim())?;
        let end_ms = subtitle_timestamp(end.split_whitespace().next().ok_or_else(invalid)?)?;
        if end_ms <= start_ms {
            return Err(invalid());
        }
        let body = block[timing + 1..].join("\n").trim().to_owned();
        if body.is_empty() || body.contains("-->") {
            return Err(invalid());
        }
        cues.push(SubtitleCue {
            text: body,
            start_ms: Some(start_ms),
            end_ms: Some(end_ms),
        });
    }
    if cues.is_empty() {
        return Err(invalid());
    }
    Ok(cues)
}

async fn append_subtitle_parts(
    tx: &mut Transaction<'_, Sqlite>,
    revision: &str,
    index: &mut usize,
    source_type: &str,
    source_media: Option<&str>,
    subtitles: &[SubtitleCue],
) -> Result<(), ApiError> {
    for cue in subtitles {
        for text in split_text(&cue.text) {
            insert_part(
                tx,
                revision,
                *index,
                if source_type == "audio" {
                    "audio"
                } else {
                    "text"
                },
                Some(&text),
                source_media,
                None,
                cue.start_ms,
                cue.end_ms,
                &json!({"source":"teacher_subtitle","audioUnderstood":true}),
            )
            .await?;
            *index += 1;
        }
    }
    Ok(())
}

